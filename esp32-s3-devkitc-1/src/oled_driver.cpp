void showFullImage(const uint8_t* src) {
  static uint8_t buf[1024];
  static const uint8_t* cachedSrc = NULL;
  if (cachedSrc != src) {
    for (int page = 0; page < 8; page++) {
      for (int col = 0; col < 128; col++) {
        uint8_t v = 0;
        for (int b = 0; b < 8; b++) {
          int py = page * 8 + b;
          int srcByte = py * 16 + (col >> 3);
          int srcBit  = 7 - (col & 7);
          if (pgm_read_byte(&src[srcByte]) & (1 << srcBit))
            v |= (1 << b);
        }
        buf[col + page * 128] = v ^ 0xFF;
      }
    }
    cachedSrc = src;
  }
  memcpy(u8g2_oled.getBufferPtr(), buf, 1024);
  u8g2_oled.sendBuffer();
}

