// ===== 动态表情包 (128x64 XBM, 来自 emoji_bitmaps.h) =====
uint8_t oledEmojiGroupCount() { return EMOJI_GROUP_COUNT; }

// 画某组的某一帧 (整屏)
static void drawEmojiFrame(uint8_t group, uint8_t frame) {
  if (group >= EMOJI_GROUP_COUNT) return;
  uint8_t frames = emojiGroupFrames[group];
  if (frame >= frames) frame = 0;
  const uint8_t* bmp = emojiGroups[group][frame];
  u8g2_oled.clearBuffer();
  u8g2_oled.drawXBM(0, 0, EMOJI_W, EMOJI_H, bmp);
  u8g2_oled.sendBuffer();
}

// 播放第 group 组动画: 按 interval 毫秒在分镜间循环(每次调用按 millis 自动选帧)
void oledPlayEmojiAnim(uint8_t group, uint32_t interval) {
  if (group >= EMOJI_GROUP_COUNT) return;
  uint8_t frames = emojiGroupFrames[group];
  if (frames == 0) return;
  uint8_t frame = (millis() / interval) % frames;
  static uint8_t lastGroup = 255, lastFrame = 255;
  if (group != lastGroup || frame != lastFrame) {   // 仅变化时刷新, 省I2C
    drawEmojiFrame(group, frame);
    lastGroup = group; lastFrame = frame;
  }
}

// 待机循环: 每 groupMs 切到下一组, 组内每 frameMs 切分镜
void oledPlayEmojiIdle(uint32_t frameMs, uint32_t groupMs) {
  uint8_t group = (millis() / groupMs) % EMOJI_GROUP_COUNT;
  oledPlayEmojiAnim(group, frameMs);
}


void oledShowBlinkingFace(uint8_t faceA, uint8_t faceB, uint32_t interval) {
  bool showA = (millis() / interval) % 2 == 0;
  oledShowFace(showA ? faceA : faceB);
}

void oledDrawBorderText(const char* top, const char* bottom) {
  if (top) {
    strncpy(borderTop, top, sizeof(borderTop) - 1);
    borderTop[sizeof(borderTop) - 1] = '\0';
  } else {
    borderTop[0] = '\0';
  }
  if (bottom) {
    strncpy(borderBottom, bottom, sizeof(borderBottom) - 1);
    borderBottom[sizeof(borderBottom) - 1] = '\0';
  } else {
    borderBottom[0] = '\0';
  }
}

